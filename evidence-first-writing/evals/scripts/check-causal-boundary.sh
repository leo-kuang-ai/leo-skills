#!/usr/bin/env bash
set -euo pipefail

output=${EVAL_FINAL_MESSAGE:-}

[[ "$output" == *"因果"* || "$output" == *"导致"* || "$output" == *"归因"* ]] || { echo "未处理因果边界" >&2; exit 1; }
refusal_re='(不能|无法|不足以|拒绝|不支持|不得|难以)[^。]{0,8}(证明|得出|断定|写出|写成|认定|归因|归为|确认|升级|下结论|因果结论|支持|说明|表明)|不成立|收窄|超出证据|超过证据|相关(性|关系)(描述|结论|表述|说法)|只能(说明|表明|支持)'
[[ "$output" =~ $refusal_re ]] || {
  echo "未拒绝或收窄因果结论（泛否定词不算，须有拒绝动词或收窄动作）" >&2
  exit 1
}
[[ "$output" == *"对照组"* || "$output" == *"缺少对照"* || "$output" == *"同期因素控制"* || "$output" == *"同期其他因素"* || "$output" == *"无法排除"* || "$output" == *"控制变量"* || "$output" == *"反事实"* ]] || {
  echo "未说明因果证据缺口" >&2
  exit 1
}
[[ "$output" != *"已经证明因果"* && "$output" != *"证明了因果"* ]] || { echo "错误声称已证明因果" >&2; exit 1; }
